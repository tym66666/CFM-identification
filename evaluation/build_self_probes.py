def claim(value: str | None = None, quote: str | None = None) -> SemanticClaim:
    if value is None:
        return SemanticClaim()
    return SemanticClaim(value=value, basis='INTERPRETATION',
                         evidence=[EvidenceQuote(source_id='business_question', quote=quote)])


def build() -> dict:
    original = {item['id']: item for item in json.loads(
        (HERE/'business_cases.json').read_text(encoding='utf-8'))['cases']}
    records = []
    for case_id, a in HAND_AUTHORED.items():
        c = BusinessCase.model_validate(original[case_id]['business_case'])
        assert all(x in c.business_question for x in (
            a['target_quote'], a['unit'][1], a['treatment'][1], a['outcome'][1],
        ))
        kwargs = {}
        if 'assignment' in a:
            kwargs['assignment_family'] = AssignmentFamily(a['assignment'])
            kwargs['assignment_law'] = claim(a['assignment_note'], a['assignment_quote'])
        if 'sample_quote' in a:
            kwargs['population_information_level'] = PopulationInformationLevel.FINITE_SAMPLE_DESCRIPTION
            kwargs['sample_data_description'] = claim('业务叙述提到观察到结果变化，不是总体算子', a['sample_quote'])
        if 'assignment_note' in a and 'assignment' not in a:
            assert a['assignment_quote'] in c.business_question
            # Deliberately leave the randomization family unresolved.
        d = DraftProblemSpec(
            target=TargetDraft(kind=TargetKind(a['target']),
                               description=claim(a['target_note'], a['target_quote'])),
            units_variables=UnitsVariablesDraft(
                analysis_unit=claim(*a['unit']),
                treatment=claim(*a['treatment']),
                outcome=claim(*a['outcome'])),
            structure=StructureDraft(unit_network=claim(*a['network']) if 'network' in a else SemanticClaim()),
            information_design=InformationDesignDraft(**kwargs),
        )
        records.append({
            'id': case_id,
            'source_question': c.business_question,
            'self_authored_interpretation': d.model_dump(mode='json'),
            'self_review_note': '我独立阅读业务句子后编写此候选；完整协议、网络、A4/A5 未从句子中得到保证。',
        })
    return {
        'type': 'ASSISTANT_AUTHORED_ILLUSTRATIVE_NORMALIZATIONS_NOT_API_EVALUATION',
        'method': 'Eight manually authored interpretations; re-evaluated by deterministic Pydantic and verbatim quote audit.',
        'independent_accuracy_claim': False,
        'items': records,
    }


def main() -> None:
    out = HERE/'self_authored_normalizations.json'
    data = build()
    out.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('Wrote', out, len(data['items']), 'hand-authored, non-independent examples')


if __name__ == '__main__':
    main()
