"""Generate source-backed v3.0 supervisor pages, no LLM or sample estimation.

27 formal cases: computed by original trusted Core and replay, not hand-marked.
Two other artifacts have *different* trust: PARTIAL research, mock LLM candidate.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
from examples.build_identification_only_demo import build_data
from examples.run_candidate_real_core import run_example
from cfm_id.business_presentation import enhance_payload

ROOT=Path(__file__).resolve().parents[1]
STEM='CFM_ID_Supervisor_Results'
COVER='CFM_ID_Coverage_Map'

def build_payload():
    gallery=build_data()
    coverage=json.loads((ROOT/'assets/coverage_fixtures'/'CFM_ID_Coverage_Atlas.json').read_text(encoding='utf-8'))
    *_,candidate,calls,lookups,real_core=run_example(off_support=True)
    *_,matched,none_calls,supported_lookups,supported_core=run_example(off_support=False)
    if real_core['q1']['status']!='POINT' or real_core['q1']['verification_level']!='CORE_REPLAY_VERIFIED':
        raise AssertionError('Real Core R1a point+replay missing')
    if real_core['q2']['status']!='UNSUPPORTED' or calls != 1 or supported_core['q2']['status']!='POINT' or none_calls != 0:
        raise AssertionError('Candidate gate violated: only real core gap may trigger one model')
    if len(gallery['cases'])!=27 or len(coverage['designs'])!=6 or len(coverage['exposures'])!=5:
        raise AssertionError('Changed baseline/gallery requires deliberate revision')
    return {
      'release':'3.0.0','schema_version':'cfm-id-v3-supervisor-trusted-gallery',
      'core_cases':gallery['cases'],'summary':gallery['core_status_counts'],
      'presentation': enhance_payload(gallery['cases']),
      'research_partial':gallery['research_partial'],
      'coverage':{k:coverage[k] for k in ('designs','exposures','topologies','scenarios','counts','routes')},
      'candidate_demo':{
        'source':'REAL_CORE_GATE__MOCK_LLM_CANDIDATE','online_llm_called':False,
        'core_off_support':real_core,'core_supported':supported_core,
        'off_support_model_calls':calls,'supported_model_calls':none_calls,
        'candidate_statuses':[q.status for q in candidate.results],
      },
      'statements':{
        'point':'Only results issued by the mathematical Core and independently replayed are certified.',
        'partial':'Star7 is an isolated bounded-outcome research demonstration, not production R4.',
        'candidate':'LLM candidate output was generated by MockProvider and is NOT a theorem.',
        'upload':'Uploading a new file does not automatically approve assumptions or certify a result.',
        'numeric':'Population symbolic identification is not a finite-sample effect estimate.',
      },
    }

def render(out_dir:Path):
    out_dir.mkdir(parents=True, exist_ok=True)
    payload=build_payload()
    safe=json.dumps(payload,ensure_ascii=False,sort_keys=True).replace('<','\\u003c').replace('>','\\u003e').replace('&','\\u0026')
    files=[]
    j=out_dir/(STEM+'.json');j.write_text(json.dumps(payload,ensure_ascii=False,sort_keys=True,indent=2)+'\n',encoding='utf-8');files.append(j)
    for name,template in ((STEM,'supervisor_template.html'),(COVER,'coverage_template.html')):
        page=(ROOT/'assets/supervisor_templates'/template).read_text(encoding='utf-8')
        assert '<!-- EMBED_DATA -->' in page
        page=page.replace('<!-- EMBED_DATA -->','<script type="application/json" id="trusted-data">'+safe+'</script>')
        t=out_dir/(name+'.html');t.write_text(page,encoding='utf-8');files.append(t)
    return files

def main():
    p=argparse.ArgumentParser();p.add_argument('--output-dir',default='assets/supervisor_templates');args=p.parse_args()
    paths=render(Path(args.output_dir)); data=json.loads(paths[0].read_text())
    print(json.dumps({'files':[str(p) for p in paths], 'verified_point_count':data['summary'].get('POINT'),
       'case_count':len(data['core_cases']), 'gate_mock_calls':[data['candidate_demo']['off_support_model_calls'],data['candidate_demo']['supported_model_calls']]},ensure_ascii=False))

if __name__=='__main__':main()
